#include <gtest/gtest.h>

#include <DatabaseFactory.h>
#include <Implementations/PostgresDatabase.h>
#include <Implementations/PostgresTable.h>
#include <Queries/CreateTableQuery.h>
#include <Exceptions/DatabaseException.h>

static std::shared_ptr<database::Database> db;

TEST(Postgres, CreateDatabase)
{
	std::string host = "127.0.0.1";

	if (char* overrideHost = std::getenv("POSTGRES_HOST"))
	{
		host = overrideHost;
	}

	ASSERT_NO_THROW(db = database::createDatabase<database::PostgresDatabase>(std::format("host={} port=5432 dbname=test user=postgres password=secret", host)));
}

TEST(Postgres, CreateTable)
{
	ASSERT_NO_THROW
	(
		(database::createTable<database::PostgresTable, database::CreateTableQuery>(
			"test_table",
			db,
			R"(CREATE TABLE IF NOT EXISTS test_table (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "doubleValue" DOUBLE PRECISION NOT NULL, "textValue" TEXT NOT NULL UNIQUE, "boolValue" BOOLEAN NOT NULL, data BYTEA))"
		))
	);

	const std::unique_ptr<database::Table>& table = db->get("test_table");
}

TEST(Postgres, Insert)
{
	const std::unique_ptr<database::Table>& table = db->get("test_table");
	std::vector<database::SqlValue> values;
	std::vector<uint8_t> bytes;

	values.emplace_back(1.1);
	values.emplace_back("first");
	values.emplace_back(true);
	values.emplace_back(nullptr);

	for (size_t i = 0; i < 128; i++)
	{
		bytes.push_back(rand() % 256);
	}

	table->execute(values, R"(INSERT INTO test_table ("doubleValue", "textValue", "boolValue", data) VALUES($1, $2, $3, $4))");

	values[0] = 2.2;
	values[1] = "second";
	values[2] = false;
	values[3] = bytes;

	table->execute(values, R"(INSERT INTO test_table ("doubleValue", "textValue", "boolValue", data) VALUES($1, $2, $3, $4))");

	ASSERT_THROW(table->execute(values, R"(INSERT INTO test_table ("doubleValue", "textValue", "boolValue", data) VALUES($1, $2, $3, $4))"), database::exception::DatabaseException);
}

TEST(Postgres, Select)
{
	const std::unique_ptr<database::Table>& table = db->get("test_table");
	std::vector<database::SqlValue> values;

	database::SqlResult result = table->execute({}, "SELECT * FROM test_table");

	ASSERT_EQ(result.size(), 2);

	for (const auto& row : result)
	{
		ASSERT_TRUE(std::holds_alternative<int64_t>(*row.at("id")));
		ASSERT_TRUE(std::holds_alternative<double>(*row.at("doubleValue")));
		ASSERT_TRUE(std::holds_alternative<std::string>(*row.at("textValue")));
		ASSERT_TRUE(std::holds_alternative<bool>(*row.at("boolValue")) || std::holds_alternative<int64_t>(*row.at("boolValue")));
		ASSERT_TRUE(std::holds_alternative<nullptr_t>(*row.at("data")) || std::holds_alternative<std::vector<uint8_t>>(*row.at("data")));
	}

	result = table->execute(values, "SELECT id FROM test_table WHERE data IS NOT NULL");

	ASSERT_EQ(result.size(), 1);
	ASSERT_EQ(result[0].at("id").get<int64_t>(), 2);
}

TEST(Postgres, Update)
{
	const std::unique_ptr<database::Table>& table = db->get("test_table");
	std::vector<database::SqlValue> values;

	values.emplace_back(5.5);
	values.emplace_back("modified");
	values.emplace_back(1);

	table->execute(values, R"(UPDATE test_table SET "doubleValue" = $1, "textValue" = $2 WHERE id = $3)");

	database::SqlResult result = table->execute({ database::SqlValue(1) }, R"(SELECT "doubleValue", "textValue" FROM test_table WHERE id = $1)");

	ASSERT_EQ(result.size(), 1);

	const auto& row = result.at(0);

	ASSERT_FLOAT_EQ(row.at("doubleValue").get<double>(), 5.5);
	ASSERT_EQ(row.at("textValue").get<std::string>(), "modified");
}

TEST(Postgres, Delete)
{
	const std::unique_ptr<database::Table>& table = db->get("test_table");

	table->execute({ database::SqlValue(2.2) }, R"(DELETE FROM test_table WHERE "doubleValue" = $1)");

	database::SqlResult result = table->execute({}, "SELECT * FROM test_table");

	ASSERT_EQ(result.size(), 1);
}

TEST(Postgres, Contains)
{
	database::Table* table = nullptr;

	ASSERT_TRUE(db->contains("test_table", &table));
	ASSERT_NE(table, nullptr);
}
